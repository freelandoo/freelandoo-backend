const INTERIORS = new Map(PLANS.map((p) => [p.level, Object.freeze(buildInterior({ ...p, version: INTERIOR_VERSION }))]));

/** Definição do interior do nível (null se o nível não tem interior). */
function interiorFor(level) {
  return INTERIORS.get(Number(level)) || null;
}

/** Tabela de conferência (REGISTRO e teste): pisos, cômodos e assentos. */
function interiorSummary() {
  return [...INTERIORS.values()].map((d) => ({
    level: d.level,
    name: d.name,
    floors: d.floors.length,
    rooms: d.floors.map((f) => f.rooms.filter((r) => r.name !== "Escada").map((r) => r.name)),
    stairs: d.stairs.length,
    seats: d.seats.length,
    area: Math.round(
      d.floors.reduce((a, f) => a + f.rooms.reduce((b, r) => b + (r.x1 - r.x0) * (r.z1 - r.z0), 0), 0)
    ),
  }));
}

module.exports = { INTERIOR_VERSION, PLANS, interiorFor, interiorSummary };
